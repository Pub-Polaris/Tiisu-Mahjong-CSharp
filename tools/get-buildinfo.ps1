# 构建时生成 Generated/BuildInfo.g.cs（版本号 = git 提交日期 yymmdd + short hash）。
# 工作区有未提交改动时在版本号后加 +；没有 git / 取不到信息时降级为 dev。
# 由 src/Tiisu.App/Tiisu.App.csproj 的 GenerateBuildInfo Target 调用。
param(
    [Parameter(Mandatory = $true)][string]$ProjectDir,
    [Parameter(Mandatory = $true)][string]$OutFile
)

$ErrorActionPreference = 'Stop'

function Invoke-Git {
    param([string[]]$GitArgs)
    try {
        $output = & git -C $ProjectDir @GitArgs 2>$null
        if ($LASTEXITCODE -ne 0) {
            return $null
        }
        return ($output | Out-String).Trim()
    }
    catch {
        return $null
    }
}

$version = 'dev'
$hash = Invoke-Git @('rev-parse', '--short', 'HEAD')
if (-not [string]::IsNullOrWhiteSpace($hash)) {
    $date = Invoke-Git @('log', '-1', '--date=format:%y%m%d', '--format=%cd')
    if (-not [string]::IsNullOrWhiteSpace($date)) {
        $version = $date + '-' + $hash
        $status = Invoke-Git @('status', '--porcelain', '--untracked-files=no')
        if (-not [string]::IsNullOrWhiteSpace($status)) {
            $version = $version + '+'
        }
    }
}

$lines = @(
    '// <auto-generated> by tools/get-buildinfo.ps1 at build time; do not edit. </auto-generated>',
    'namespace Tiisu.App',
    '{',
    'internal static class BuildInfo',
    '{',
    ('    internal const string Version = "{0}";' -f $version),
    '}',
    '}'
)
$content = ($lines -join "`r`n") + "`r`n"

$dir = [IO.Path]::GetDirectoryName($OutFile)
if (-not [IO.Directory]::Exists($dir)) {
    [IO.Directory]::CreateDirectory($dir) | Out-Null
}

$existing = $null
if ([IO.File]::Exists($OutFile)) {
    $existing = [IO.File]::ReadAllText($OutFile)
}

if ($existing -ne $content) {
    [IO.File]::WriteAllText($OutFile, $content, (New-Object System.Text.UTF8Encoding($false)))
}

Write-Output $version
